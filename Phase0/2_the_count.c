/*
 * CHALLENGE: The Count
 * DESCRIPTION: Uses a loop to count from 1 to 10 and prints each number.
 * TOPICS: For Loop, Basic Counting
 */

#include <stdio.h>

int main() {
    int x;
    
    // Iterate from 1 up to and including 10
    for (x = 1; x <= 10; x++) {
        printf("%d\n", x);
    }
    
    return 0;
}
